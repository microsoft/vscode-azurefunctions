import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { getNodeBindings, renderBindings } from './update.mjs';

const sdkDeclaration = `
interface TriggerCallbackPayload<T> { body: { value: T[] }; }
export interface EventModel { id: string; }
export interface ActionResponse { action: string; }
export declare const ExampleTriggerOperations: {
    readonly OnArrived: "ArrivedV2";
    readonly OnMemberAdded: "MemberAdd";
    readonly OnGeneric: "GenericEvent";
    readonly OnUnsupported: "UnsupportedEvent";
};
/** Typed callback payload for trigger operation 'ArrivedV2'. */
export type ExampleOnArrivedTriggerPayload = TriggerCallbackPayload<EventModel>;
/** Typed callback payload for trigger operation 'MemberAdd'. */
export type ExampleOnMemberAddedTriggerPayload = TriggerCallbackPayload<Record<string, unknown>>;
/** Typed callback payload for trigger operation 'GenericEvent'. */
export type ExampleOnGenericTriggerPayload = TriggerCallbackPayload<EventModel>;
`;

const extensionDeclaration = `
import type { EventModel } from '../../connectors/dist/esm/generated/ExampleExtensions.js';
export declare const connectors: {
    differentGroupName: {
        onArrived(name: string, options: { handler: (event: { items: EventModel[] }) => void }): void;
        onMemberAdded(name: string, options: { handler: (event: { items: Record<string, unknown>[] }) => void }): void;
    };
};
`;

async function fixture(t, sdk = sdkDeclaration) {
    const root = await mkdtemp(path.join(tmpdir(), 'azfunc-sdk-fixture-'));
    t.after(() => rm(root, { recursive: true, force: true }));
    const sdkPath = path.join(root, '@azure', 'connectors', 'dist', 'esm', 'generated');
    const extensionPath = path.join(root, '@azure', 'functions-extensions-connectors', 'types');
    await mkdir(sdkPath, { recursive: true });
    await mkdir(extensionPath, { recursive: true });
    await writeFile(path.join(sdkPath, 'ExampleExtensions.d.ts'), sdk);
    await writeFile(path.join(extensionPath, 'index.d.ts'), extensionDeclaration);
    return root;
}

test('joins SDK operation identifiers, exact model declarations, and exported helpers without connector names', async t => {
    const bindings = await getNodeBindings(await fixture(t));
    assert.deepEqual(bindings.example.ArrivedV2, {
        itemType: 'EventModel',
        importPath: '@azure/connectors/generated/ExampleExtensions',
        helper: 'differentGroupName.onArrived',
    });
    assert.deepEqual(bindings.example.MemberAdd, {
        itemType: 'Record<string, unknown>',
        importPath: undefined,
        helper: 'differentGroupName.onMemberAdded',
    });
    assert.deepEqual(bindings.example.GenericEvent, {
        itemType: 'EventModel',
        importPath: '@azure/connectors/generated/ExampleExtensions',
    });
    assert.equal(bindings.example.UnsupportedEvent, undefined);
});

test('rejects changed callback metadata rather than silently dropping typed events', async t => {
    const root = await fixture(t, sdkDeclaration.replaceAll('Typed callback payload', 'Changed documentation'));
    await assert.rejects(getNodeBindings(root), /Unrecognized SDK callback declaration/);
});

test('rejects callbacks that are absent from the SDK operation registry', async t => {
    const root = await fixture(t, sdkDeclaration.replace("trigger operation 'GenericEvent'", "trigger operation 'MissingEvent'"));
    await assert.rejects(getNodeBindings(root), /absent from the SDK operation registry/);
});

test('renders a deterministic snapshot and preserves runtime-specific fallbacks', () => {
    const csharp = { example: { DotnetOnly: { namespace: 'Example.Models', payloadType: 'ExamplePayload' } } };
    const node = { z: { Second: { itemType: 'unknown' } }, a: { First: { itemType: 'string' } } };
    assert.equal(renderBindings(node, csharp, {}), renderBindings({ a: node.a, z: node.z }, csharp, {}));
    assert.match(renderBindings({}, csharp, {}), /"DotnetOnly",\{"typescript":\{\},"csharp":/);
    assert.match(renderBindings({}, csharp, {}), /Generated by npm run update-connector-sdk-bindings/);
});
